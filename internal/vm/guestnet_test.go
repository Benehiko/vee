func TestGuestChecksDNSLeak(t *testing.T) {
	cfg := &VMConfig{VPNProvider: "generic"}
	host := &HostNetwork{PublicIP: "82.1.2.3"}
	guest := &GuestNetwork{
		Interfaces: []qemu.GuestNetworkInterface{
			{Name: "enp1s0", IPAddresses: []qemu.GuestIPAddress{{IPAddress: "192.168.1.5", Prefix: 24, IPAddressType: "ipv4"}}},
			{Name: "wg0", IPAddresses: []qemu.GuestIPAddress{{IPAddress: "10.5.0.2", Prefix: 32, IPAddressType: "ipv4"}}},
		},
		DefaultRoute: "dev wg0",
		DNSServers:   []string{"192.168.1.1"},
		UFW:          UFWState{Available: true, Active: true, DefaultOutgoing: "deny", RuleCount: 5},
		VPN:          VPNState{Provider: "generic", Available: true, Connected: true, Endpoint: "185.65.135.1:51820"},
		EgressIP:     "185.65.135.1",
		DNSEgressIP:  "185.65.135.1",
	}
	checks := guestChecks(cfg, NetworkOptions{}, host, guest)
	got := map[string]string{}
	for _, c := range checks {
		got[c.Name] = c.Status
	}
	if got["guest:dns-leak"] != NetCheckFail {
		t.Errorf("dns-leak = %q, want fail (LAN resolver)", got["guest:dns-leak"])
	}
	for _, name := range []string{"guest:route", "guest:ufw", "guest:killswitch", "guest:vpn", "guest:egress-ip", "guest:dns-egress"} {
		if got[name] != NetCheckPass {
			t.Errorf("%s = %q, want pass", name, got[name])
		}
	}

	// VPN-egress DNS passes; egress matching the host fails.
	guest.DNSServers = []string{"103.86.96.100"}
	guest.EgressIP = "82.1.2.3"
	checks = guestChecks(cfg, NetworkOptions{}, host, guest)
	got = map[string]string{}
	for _, c := range checks {
		got[c.Name] = c.Status
	}
	if got["guest:dns-leak"] != NetCheckPass {
		t.Errorf("dns-leak = %q, want pass", got["guest:dns-leak"])
	}
	if got["guest:egress-ip"] != NetCheckFail {
		t.Errorf("egress-ip = %q, want fail (matches host)", got["guest:egress-ip"])
	}
}

