func TestParseIPAddrBrief(t *testing.T) {
	input := `1: lo    inet 127.0.0.1/8 scope host lo\       valid_lft forever preferred_lft forever
2: enp1s0    inet 192.168.1.5/24 brd 192.168.1.255 scope global dynamic enp1s0\       valid_lft 85822sec preferred_lft 85822sec
2: enp1s0    inet6 fe80::5054:ff:fe12:3456/64 scope link \       valid_lft forever preferred_lft forever
3: wg0    inet 10.5.0.2/32 scope global wg0\       valid_lft forever preferred_lft forever
`
	ifaces := ParseIPAddrBrief(input)
	if len(ifaces) != 3 {
		t.Fatalf("got %d interfaces, want 3", len(ifaces))
	}
	if ifaces[1].Name != "enp1s0" || len(ifaces[1].IPAddresses) != 2 {
		t.Errorf("enp1s0 parsed wrong: %+v", ifaces[1])
	}
	if ifaces[1].IPAddresses[0].IPAddress != "192.168.1.5" || ifaces[1].IPAddresses[0].Prefix != 24 {
		t.Errorf("enp1s0 addr parsed wrong: %+v", ifaces[1].IPAddresses[0])
	}
	if ifaces[2].Name != "wg0" || ifaces[2].IPAddresses[0].IPAddress != "10.5.0.2" {
		t.Errorf("wg0 parsed wrong: %+v", ifaces[2])
	}
}

