func TestParseDefaultRoute(t *testing.T) {
	tests := []struct {
		name    string
		input   string
		wantVia string
		wantDev string
	}{
		{
			name:    "dhcp lan route",
			input:   "default via 192.168.1.1 dev enp1s0 proto dhcp src 192.168.1.5 metric 100",
			wantVia: "192.168.1.1",
			wantDev: "enp1s0",
		},
		{
			name:    "nordlynx no gateway",
			input:   "default dev nordlynx table 205 scope link",
			wantVia: "",
			wantDev: "nordlynx",
		},
		{
			name:    "wireguard route",
			input:   "default dev wg0 scope link",
			wantVia: "",
			wantDev: "wg0",
		},
		{
			name:    "empty",
			input:   "",
			wantVia: "",
			wantDev: "",
		},
		{
			name:    "no default route",
			input:   "192.168.1.0/24 dev enp1s0 proto kernel scope link",
			wantVia: "",
			wantDev: "",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			via, dev := ParseDefaultRoute(tt.input)
			if via != tt.wantVia || dev != tt.wantDev {
				t.Errorf("ParseDefaultRoute() = (%q, %q), want (%q, %q)", via, dev, tt.wantVia, tt.wantDev)
			}
		})
	}
}

func TestParseDNSServers(t *testing.T) {
	tests := []struct {
		name  string
		input string
		want  []string
	}{
		{
			name:  "resolv.conf",
			input: "# Generated by NetworkManager\nnameserver 103.86.96.100\nnameserver 103.86.99.100\nsearch lan\n",
			want:  []string{"103.86.96.100", "103.86.99.100"},
		},
		{
			name:  "resolvectl",
			input: "Global: 1.1.1.1 8.8.8.8\nLink 2 (enp1s0): 192.168.1.1\n",
			want:  []string{"1.1.1.1", "8.8.8.8", "192.168.1.1"},
		},
		{
			name:  "resolvectl with iface suffix",
			input: "Link 2 (enp1s0): 192.168.1.1 fe80::1%enp1s0\n",
			want:  []string{"192.168.1.1", "fe80::1"},
		},
		{
			name:  "systemd stub resolv.conf",
			input: "nameserver 127.0.0.53\noptions edns0 trust-ad\n",
			want:  []string{"127.0.0.53"},
		},
		{
			name:  "dedup",
			input: "nameserver 1.1.1.1\nnameserver 1.1.1.1\n",
			want:  []string{"1.1.1.1"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := ParseDNSServers(tt.input)
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("ParseDNSServers() = %v, want %v", got, tt.want)
			}
		})
	}
}

func TestParseUFWStatus(t *testing.T) {
	activeDeny := `Status: active
Logging: on (low)
Default: deny (incoming), deny (outgoing), disabled (routed)
New profiles: skip

To                         Action      From
--                         ------      ----
22/tcp (OpenSSH)           ALLOW IN    Anywhere
8080/tcp                   ALLOW IN    Anywhere
Anywhere on wg0            ALLOW OUT   Anywhere
22/tcp                     ALLOW OUT   Anywhere
`
	got := ParseUFWStatus(activeDeny)
	if !got.Active {
		t.Error("expected Active")
	}
	if got.DefaultOutgoing != "deny" {
		t.Errorf("DefaultOutgoing = %q, want deny", got.DefaultOutgoing)
	}
	if got.RuleCount != 4 {
		t.Errorf("RuleCount = %d, want 4", got.RuleCount)
	}

	inactive := "Status: inactive\n"
	got = ParseUFWStatus(inactive)
	if got.Active {
		t.Error("expected inactive")
	}

	allowOut := "Status: active\nDefault: deny (incoming), allow (outgoing), disabled (routed)\n"
	got = ParseUFWStatus(allowOut)
	if got.DefaultOutgoing != "allow" {
		t.Errorf("DefaultOutgoing = %q, want allow", got.DefaultOutgoing)
	}
}

func TestParseNordVPNStatus(t *testing.T) {
	connected := "\r-\r\\\rStatus: Connected\nHostname: de1234.nordvpn.com\nIP: 185.130.184.90\nCountry: Germany\nCity: Frankfurt\nCurrent technology: NORDLYNX\nTransfer: 1.2 MiB received, 0.5 MiB sent\n"
	ok, server, detail := ParseNordVPNStatus(connected)
	if !ok {
		t.Error("expected connected")
	}
	if server != "de1234.nordvpn.com" {
		t.Errorf("server = %q", server)
	}
	if detail == "" {
		t.Error("expected non-empty detail")
	}

	disconnected := "Status: Disconnected\n"
	ok, _, _ = ParseNordVPNStatus(disconnected)
	if ok {
		t.Error("expected disconnected")
	}

	daemonDead := "We couldn't reach System Daemon.\n"
	ok, _, detail = ParseNordVPNStatus(daemonDead)
	if ok {
		t.Error("expected disconnected when daemon is unreachable")
	}
	if detail != "We couldn't reach System Daemon." {
		t.Errorf("detail = %q, want the raw daemon error", detail)
	}
}

