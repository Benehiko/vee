func TestParseWGShow(t *testing.T) {
	up := `interface: wg0
  public key: abc123=
  private key: (hidden)
  listening port: 51820

peer: def456=
  endpoint: 185.65.135.1:51820
  allowed ips: 0.0.0.0/0
  latest handshake: 1 minute, 5 seconds ago
  transfer: 12.5 MiB received, 1.2 MiB sent
`
	endpoint, handshake := ParseWGShow(up)
	if endpoint != "185.65.135.1:51820" {
		t.Errorf("endpoint = %q", endpoint)
	}
	if handshake != "handshake 1 minute, 5 seconds ago" {
		t.Errorf("handshake = %q", handshake)
	}

	never := "interface: wg0\n  public key: abc123=\n\npeer: def456=\n  endpoint: 185.65.135.1:51820\n  allowed ips: 0.0.0.0/0\n"
	_, handshake = ParseWGShow(never)
	if handshake != "" {
		t.Errorf("handshake = %q, want empty (never completed)", handshake)
	}
}

